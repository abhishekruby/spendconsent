import assert from 'node:assert/strict';
import {exactCart,boundAttempt,financialControl} from './record-guards.mjs';
const request={id:'request',review:{id:'review',currency:'USD',total_cents:4180},attempt:{id:'attempt',state:'AWAITING_BUYER',currency:'USD',total_cents:4180,provider_order_id:'sandbox-order'}};
const entry={request:'request',review:'review',attempt:'attempt',total_cents:4180,state:'reserved',provider_order:'sandbox-order'};
exactCart(request); boundAttempt(request,entry);
financialControl({kind:'pay',popup:true,name:'Pay now'},request,entry);
for (const total of [-1,0,10000,10001,1.5]) assert.throws(()=>exactCart({...request,review:{...request.review,total_cents:total}}));
assert.throws(()=>boundAttempt(request,{...entry,request:'other'}));
assert.throws(()=>boundAttempt(request,{...entry,attempt:'other'}));
assert.throws(()=>boundAttempt({...request,attempt:{...request.attempt,total_cents:9999}},entry));
assert.throws(()=>boundAttempt({...request,attempt:{...request.attempt,currency:'EUR'}},entry));
assert.throws(()=>boundAttempt(request,{...entry,provider_order:'other'}));
assert.throws(()=>financialControl({kind:'pay',popup:true,name:'Pay now',selector:'button'},request,entry));
assert.throws(()=>financialControl({kind:'pay',popup:true,name:'Pay now',exact:false},request,entry));
assert.throws(()=>financialControl({kind:'pay',name:'Pay now'},request,entry));
assert.throws(()=>financialControl({kind:'pay',popup:true,name:'Pay now'},request,{...entry,state:'payment-click-attempted'}));
const paid={...request,attempt:{...request.attempt,state:'PAID'}};
financialControl({kind:'open-refund',name:'Cancel order & refund'},paid,entry);
financialControl({kind:'refund',name:'Yes, cancel and refund $41.80'},paid,entry);
assert.throws(()=>financialControl({kind:'open-refund',name:'Yes, cancel and refund $41.80'},paid,entry));
assert.throws(()=>financialControl({kind:'refund',name:'Cancel order & refund'},paid,entry));
assert.throws(()=>financialControl({kind:'refund',name:'Yes, cancel and refund $47.60'},paid,entry));
assert.throws(()=>financialControl({kind:'refund',popup:true,name:'Pay now'},paid,entry));
console.log('PASS: sandbox amount, purchase binding, financial controls, duplicate attempts and full-refund guards.');
